// ── Helper: get translation for current page & lang ─────────
function getT(page) {
  const lang = localStorage.getItem('dl_lang') || 'en';
  const pageT = DL_TRANSLATIONS[page] && DL_TRANSLATIONS[page][lang]
    ? DL_TRANSLATIONS[page][lang]
    : DL_TRANSLATIONS[page]['en'];
  const commonT = DL_TRANSLATIONS.common[lang] || DL_TRANSLATIONS.common['en'];
  return { ...commonT, ...pageT };
}

// ── Helper: apply translations to elements by data-i18n ─────
function applyTranslations(page) {
  const t = getT(page);
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) {
      if (el.tagName === 'INPUT' && el.placeholder !== undefined) {
        el.placeholder = t[key];
      } else {
        el.innerHTML = t[key];
      }
    }
  });
  // Also set document title if defined
  if (t.pageTitle) document.title = 'DL Journey — ' + t.pageTitle.replace(/[🎉📋📍]/g, '').trim();
}